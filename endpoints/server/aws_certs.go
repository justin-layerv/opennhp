// GetAWSCertificate returns the RSA-2048 certificate for the given AWS region.
// Returns empty string if the region is not supported.
func GetAWSCertificate(region string) string {
	return AWSRegionCertificates[region]
}

// SupportedAWSRegions returns a list of AWS regions that have certificates configured.
func SupportedAWSRegions() []string {
	regions := make([]string, 0, len(AWSRegionCertificates))
	for region := range AWSRegionCertificates {
		regions = append(regions, region)
	}
	return regions
}
